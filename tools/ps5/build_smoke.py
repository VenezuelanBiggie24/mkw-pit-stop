def git(repo: Path, *args: str) -> str:
    return subprocess.check_output(["git", "-C", str(repo), *args], text=True).strip()


def require_checkout(repo: Path, revision: str) -> None:
    if not repo.is_dir() or git(repo, "rev-parse", "HEAD") != revision:
        raise SystemExit(f"{repo} must be checked out at {revision}")
    if git(repo, "status", "--porcelain", "--untracked-files=no"):
        raise SystemExit(f"{repo} has tracked changes; use the pinned sources")


def write_changed(path: Path, data: bytes) -> None:
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def probe_layouts() -> bytes:
    # Reserve the complete module slot, even though the game itself is absent.
    # The desktop trial uses the first addresses its runtime would try.
    candidate = PLACEMENTS["ps5-smoke"]
    # Hookshot's PS5 beta (a3551c6) reserved [64, 128) GiB in 16 GiB pieces.
    # See docs/research.md. Keep this survey independent of the runtime profile.
    alternate = replace(candidate, low_base=32 * GIB, alias_base=64 * GIB)
    low36 = PLACEMENTS["ps5-low36"]
    validate_placement(alternate)
    validate_placement(low36)
    trials = (
        ("low36", low36, False),
        ("low36", low36, True),
        ("desktop", PLACEMENTS[DEFAULT], False),
        ("candidate", candidate, False),
        ("candidate", candidate, True),
        ("alternate", alternate, False),
        ("alternate", alternate, True),
    )
    lines = ["/* Generated by build_smoke.py using recomp/layout.py. */"]
    entries = []
    max_ranges = 0
    for trial, placement, segmented in trials:
        mode = "segmented" if segmented else "whole"
        array = f"{trial}_{mode}"
        low, alias = first_lower_ranges(placement)
        lines.append(f"static const Range {array}[] = {{")
        count = 0
        for name, base, size, cap in (
            ("modules", placement.module_base, placement.kernel_base - placement.module_base, 0),
            ("kernel", placement.kernel_base, KERNEL_SIZE, 0),
            ("host functions", placement.hostfn_base, HOSTFN_SIZE, 0),
            ("stack and heap", low, LOW_SIZE, 4 * GIB),
            ("alias", alias, ALIAS_SIZE, 16 * GIB),
        ):
            step = cap if segmented and cap else size
            for offset in range(0, size, step):
                piece = min(step, size - offset)
                lines.append(f'    {{"{name}", {base + offset:#x}ull, {piece:#x}ull}},')
                count += 1
        lines.append("};")
        max_ranges = max(max_ranges, count)
        try_exclusive = "true" if trial == "alternate" else "false"
        entries.append(f'    {{"{trial} {mode}", {array}, sizeof {array} / sizeof *{array}, {try_exclusive}}},')
    lines += [f"enum {{ MAX_TRIAL_RANGES = {max_ranges} }};", "static const LayoutTrial layout_trials[] = {", *entries, "};"]
    return ("\n".join(lines) + "\n").encode()


def backing_layout() -> bytes:
    layout = PLACEMENTS["ps5-high144"]
    values = {
        "STACK_BASE": layout.low_base,
        "STACK_SIZE": LOW_SIZE,
        "ALIAS_BASE": layout.alias_base,
        "ALIAS_SIZE": ALIAS_SIZE,
        "MODULE_BASE": layout.module_base,
        "MODULE_SIZE": layout.kernel_base - layout.module_base,
        "KERNEL_BASE": layout.kernel_base,
        "KERNEL_SIZE": KERNEL_SIZE,
        "HOSTFN_BASE": layout.hostfn_base,
        "HOSTFN_SIZE": HOSTFN_SIZE,
    }
    return ("/* Generated by build_smoke.py using recomp/layout.py. */\n"
            + "".join(f"#define PS5_BACKING_{name} {value:#x}ull\n" for name, value in values.items())).encode()


AMPR_STUB = '"$work/link/stubs/libSceAmpr.so"'
AGC_DRIVER_STUB = '"$work/link/stubs/libSceAgcDriver.so"'


def link_libsceampr(title: Path, on: bool) -> None:
    """The page-table probe imports libSceAmpr, which the SDK has no stub for: a title's sceKernelDlsym finds nothing
    on the console (PS5_Vulkan docs/HARDWARE_FINDINGS.md), so the import must be linked. Adds tools/ps5/ampr_stub.c as
    libSceAmpr.prx next to the template's AGC stubs, in the LLVM link, the null-import check and the native link, as
    link-title.sh does for libSceAgcDriver; removes it again for the other titles."""
    path = title / "ps5/tools/link-title.sh"
    text = path.read_text(encoding="utf-8")
    build = (f'cc -std=c11 -O2 -fPIC -c "{HERE / "ampr_stub.c"}" -o "$work/link/obj/libSceAmpr_stub.o"  # mkw-ampr\n'
             '"$sdk/bin/prospero-lld" --shared -soname libSceAmpr.prx -o "$work/link/stubs/libSceAmpr.so" '
             '"$work/link/obj/libSceAmpr_stub.o"  # mkw-ampr\n')
    anchor = "stub libSceAgcDriver vendor/ps5/sdk/stubs/agc_driver_canary_link_stub.c\n"
    pairs = ((f"{AGC_DRIVER_STUB} \\\n", f"{AGC_DRIVER_STUB} {AMPR_STUB} \\\n"),
             (f"{AGC_DRIVER_STUB}; do", f"{AGC_DRIVER_STUB} {AMPR_STUB}; do"),
             (f"--stub {AGC_DRIVER_STUB} --module-sdk", f"--stub {AGC_DRIVER_STUB} --stub {AMPR_STUB} --module-sdk"))
    new = "".join(line for line in text.splitlines(keepends=True) if "# mkw-ampr" not in line)
    for plain, with_ampr in pairs:
        new = new.replace(with_ampr, plain)
    if on:
        if anchor not in new or any(plain not in new for plain, _ in pairs):
            raise SystemExit("link-title.sh changed: cannot add the libSceAmpr stub")
        new = new.replace(anchor, anchor + build)
        for plain, with_ampr in pairs:
            new = new.replace(plain, with_ampr)
    if new != text:
        path.write_text(new, encoding="utf-8")


def prepare(template: Path, title: Path, probe: str | None, amm: dict[str, int] | None = None) -> None:
    generator = template / "ps5/tools/new-title.py"
    if not title.exists():
        # The generator initializes a separate project in build/, which its
        # notice staging uses to retrieve the foundation's license files.
        identity = dict(os.environ, GIT_AUTHOR_NAME=TITLE_NAME, GIT_COMMITTER_NAME=TITLE_NAME,
                        GIT_AUTHOR_EMAIL="smoke@localhost", GIT_COMMITTER_EMAIL="smoke@localhost")
        with tempfile.TemporaryDirectory(dir=title.parent) as tmp:
            staged = Path(tmp) / "title"
            subprocess.run([sys.executable, str(generator), str(staged), "--title-id", TITLE_ID,
                            "--name", TITLE_NAME, "--refresh", "60", "--flexible-memory", "448"],
                           env=identity, check=True)
            (staged / "ps5/sce_sys/icon0.png").unlink(missing_ok=True)
            staged.rename(title)

    icon = title / "ps5/sce_sys/icon0.png"
    if not icon.exists():
        icon.write_bytes(png(512))
    param_path = title / "ps5/sce_sys/param.json"
    param = json.loads(param_path.read_text(encoding="utf-8"))
    # param.json "amm" keys only on request (--amm-pagetable-mib, --amm-multimap-gib): the default title keeps the
    # console's defaults ("[Amm config] Page table memory : 64 MiB, ... MultiMap VA range size 0 GiB").
    # multimapVaRangeInGib: psdevwiki PS5 Param.json (amm section, optional integer, example 512).
    want = {key: value for key, value in (amm or {}).items() if value}
    if param.get("amm", {}) != want:
        if want:
            param["amm"] = want
        else:
            param.pop("amm", None)
        param_path.write_text(json.dumps(param, indent=2) + "\n", encoding="utf-8")
    link_libsceampr(title, probe == "page-table")
    sample = title / f"examples/{SAMPLE}"
    write_changed(sample / f"{SAMPLE}.cpp", (HERE / "smoke.cpp").read_bytes())
    write_changed(sample / "probe.c", (HERE / "probe.c").read_bytes())
    write_changed(sample / "probe_layouts.h", probe_layouts())
    write_changed(sample / "backing_layout.h", backing_layout())
    write_changed(sample / "guest_layout.h", ("#pragma once\n" + placement_defines("ps5-high144")).encode())
    write_changed(sample / "memory_probe.c", (HERE / "memory_probe.c").read_bytes())
    write_changed(sample / "runtime_probe.c", (HERE / "runtime_probe.c").read_bytes())
    for name in ("ps5_memory.c", "ps5_memory.h", "ps5_mixed.c", "ps5_mixed.h"):
        write_changed(sample / name, (PS5_PLATFORM / name).read_bytes())
    cmake = title / "ps5/CMakeLists.txt"
    source = f"\tsrc/main.cpp\n\t${{ROOT}}/examples/{SAMPLE}/probe.c\n"
    text = cmake.read_text()
    if source not in text:
        if text.count("\tsrc/main.cpp\n") != 1:
            raise SystemExit("Could not locate the pinned template's source list")
        text = text.replace("\tsrc/main.cpp\n", source)
    native_sources = ("if(NOT PS5_HOST_REFERENCE)\n"
                      f"\ttarget_sources(samples PRIVATE ${{ROOT}}/examples/{SAMPLE}/memory_probe.c\n"
                      f"\t\t${{ROOT}}/examples/{SAMPLE}/ps5_memory.c)\n"
                      "endif()\n")
    mixed_sources = ("if(NOT PS5_HOST_REFERENCE)\n"
                     f"\ttarget_sources(samples PRIVATE ${{ROOT}}/examples/{SAMPLE}/ps5_mixed.c)\n"
                     "endif()\n")
    target = "target_compile_definitions(samples PRIVATE\n"
    runtime = "${ROOT}/" + os.path.relpath(ROOT / "runtime", title)
    dispatch_sources = (
        f'target_sources(samples PRIVATE "{runtime}/cpu/dispatch.c"\n'
        f'\t"${{ROOT}}/examples/{SAMPLE}/runtime_probe.c")\n'
        f'target_include_directories(samples PRIVATE "{runtime}" "{runtime}/cpu" "{runtime}/core/base"\n'
        f'\t"${{ROOT}}/examples/{SAMPLE}")\n'
    )
    if text.count(target) != 1:
        raise SystemExit("Could not locate the pinned template's sample target")
    for sources in (native_sources, mixed_sources, dispatch_sources):
        if sources not in text:
            text = text.replace(target, sources + target)
    if probe:
        definition = {"query-memory": "MKW_PS5_QUERY_SMOKE", "dualsense": "MKW_PS5_DUALSENSE_SMOKE",
                      "alias-subrange": "MKW_PS5_ALIAS_SMOKE", "page-table": "MKW_PS5_PAGE_TABLE_SMOKE"}[probe]
        flag = ("if(NOT PS5_HOST_REFERENCE)\n"
                f"\ttarget_compile_definitions(samples PRIVATE {definition})\n"
                "endif()\n")
        if flag not in text:
            text = text.replace(target, flag + target)
        # The pinned template links the sample target's compiled objects
        # directly. Add the separately compiled probe to both the command and
        # its dependencies so any update relinks the package.
        bundle = f'"${{ROOT}}/{probe}.o"'
        for line in text.splitlines(keepends=True):
            if ((line.startswith("\tCOMMAND bash ") or line.startswith("\tDEPENDS samples "))
                    and '"$<TARGET_OBJECTS:samples>"' in line and bundle not in line):
                text = text.replace(line, line.replace('"$<TARGET_OBJECTS:samples>"',
                                                       f'"$<TARGET_OBJECTS:samples>" {bundle}'))
        if text.count(bundle) != 2:
            raise SystemExit("Could not locate the pinned template's native link rule")
    write_changed(cmake, text.encode())

    # The smoke test clears a render pass. Its starter model, font and shaders
    # are unnecessary because it uses neither a graphics pipeline nor an overlay.
    manifest = title / "ps5/assets.json"
    assets = json.loads(manifest.read_text())
    assets["assets"] = []
    write_changed(manifest, (json.dumps(assets, indent=2) + "\n").encode())
    shaders = title / f"shaders/glsl/{SAMPLE}"
    if shaders.exists():
        shutil.rmtree(shaders)


def sha256(path: Path) -> str:
    with path.open("rb") as file:
        return hashlib.file_digest(file, "sha256").hexdigest()


def require_radv(vulkan: Path) -> tuple[Path, str]:
    from build_radv import ensure_radv

    archive, digest = ensure_radv(vulkan, MESA, RADV_SDK)
    provenance = vulkan / ".deps/native/radv-release/PROVENANCE.txt"
    info = dict(line.split(": ", 1) for line in provenance.read_text().splitlines() if ": " in line)
    expected = {"revision": MESA, "sdk": RADV_SDK, "assertions": "off", "archive sha256": digest}
    for key, value in expected.items():
        if info.get(key) != value:
            raise SystemExit(f"{provenance}: expected {key}: {value}")
    return archive, digest


def build_probe(title: Path, env: dict[str, str], probe: str, defines: tuple[str, ...] = ()) -> None:
    sdk = Path(subprocess.check_output(["bash", str(title / "ps5/tools/setup-sdk.sh")],
                                      env=env, text=True).strip())
    runtime = ROOT / "runtime"
    includes = (runtime, runtime / "cpu", runtime / "core/base", title / "ps5/src", title / f"examples/{SAMPLE}")
    flags = []
    if probe == "query-memory":
        includes += (runtime / "core/boot", runtime / "core/kernel")
        sources = (HERE / "query_probe.c", runtime / "core/kernel/svc_query.c", runtime / "core/memory/memory.c",
                   PS5_PLATFORM / "ps5_guest_span.c")
        flags.append("-DMKW_PS5_QUERY_SPAN_FIXTURE")
        roots = ("mkw_query_memory_probe",)
    elif probe == "dualsense":
        includes += (runtime / "input",)
        sources = (HERE / "pad_probe.c", runtime / "input/ps5_input.c", runtime / "input/input_map.c")
        roots = ("mkw_pad_probe_start", "mkw_pad_probe_frame", "mkw_pad_probe_finish")
    elif probe == "page-table":
        includes += (title / "external",)
        # The template's Vulkan entry points are volk's function-pointer variables: a plain
        # <vulkan/vulkan.h> prototype call jumps into the variable itself (console run: SIGSEGV
        # executing vkCreateImage's data address).
        flags += ["-DVK_NO_PROTOTYPES", "-include", str(title / "ps5/third_party/volk/volk.h")]
        sources = (HERE / "page_table_probe.c",)
        roots = ("mkw_page_table_probe",)
        flags += [f"-D{name}" for name in defines]   # GPU reads that may fault the GPU and end the title
    else:
        sources = (HERE / "alias_probe.c",)
        roots = ("mkw_ps5_alias_subrange_probe",)
    with tempfile.TemporaryDirectory(dir=title) as tmp:
        objects = []
        for source in sources:
            obj = Path(tmp) / (source.stem + ".o")
            # PS5 Clang emits jump-table metadata that can refer to functions
            # removed by the probe's relocatable link.
            subprocess.run([str(sdk / "bin/prospero-clang"), "-std=gnu11", "-O2", "-fPIC",
                            "-ffunction-sections", "-fdata-sections", "-fno-jump-tables",
                            *flags,
                            *(f"-I{path}" for path in includes), "-c", str(source), "-o", str(obj)],
                           env=env, check=True)
            objects.append(str(obj))
        bundle = Path(tmp) / f"{probe}.o"
        # The SDK's final-link script merges every text section. Use its LLVM
        # linker directly here to retain only the selected call graph.
        subprocess.run([str(sdk / "bin/ld.lld"), "-r", "--gc-sections",
                        *(flag for root in roots for flag in ("-u", root)),
                        *objects, "-o", str(bundle)], env=env, check=True)
        write_changed(title / bundle.name, bundle.read_bytes())


def build(title: Path, vulkan: Path, mesa: Path, sdk: Path, probe: str | None, defines: tuple[str, ...] = ()) -> Path:
    archive, radv_hash = require_radv(vulkan)
    native_tool = vulkan / "build/host/ps5-native-tool"
    libc = vulkan / "runtime/libc.prx"
    for path in (native_tool, libc):
        if not path.is_file():
            raise SystemExit(f"Missing build prerequisite {path} (see tools/ps5/README.md)")

    # The template looks for Mesa and SDK source as siblings of the generated
    # project when it stages license notices.
    work = title.parent
    for checkout in (vulkan, mesa, sdk):
        link = work / checkout.name
        if link.is_symlink() and link.resolve() != checkout.resolve():
            link.unlink()
        if not link.is_symlink():
            link.symlink_to(checkout, target_is_directory=True)
    env = dict(os.environ, PS5_VULKAN_DIR=str(work / vulkan.name),
               PS5_PAYLOAD_SDK_FORK=str(sdk), RADV_ARCHIVE=str(archive))
    if probe:
        llvm_config = shutil.which("llvm-config-22")
        if llvm_config:
            env.setdefault("LLVM_CONFIG", llvm_config)
        build_probe(title, env, probe, defines)

    folder = title / "dist" / TITLE_ID
    native = title / "build/ps5"
    stamp = work / "native-inputs.json"
    # The template's Ninja link rule does not track dependencies outside its
    # object list. Track the verified archive and the inputs copied to dist/.
    metadata = title / "ps5/sce_sys"
    inputs = [str(vulkan), str(mesa), str(sdk), radv_hash,
              *(sha256(path) for path in (native_tool, libc, metadata / "param.json", metadata / "icon0.png"))]
    state = json.dumps(inputs) + "\n"
    if not stamp.exists() or stamp.read_text() != state:
        if native.exists():
            shutil.rmtree(native)
        if folder.exists():
            shutil.rmtree(folder)
        stamp.write_text(state)

    outputs = [folder / name for name in ("eboot.bin", "sce_sys/param.json", "sce_sys/icon0.png",
                                          "licenses/components.json")]
    if any(not path.is_file() or not path.stat().st_size for path in outputs):
        (native / "eboot.elf").unlink(missing_ok=True)
    try:
        subprocess.run(["bash", str(title / "ps5/tools/build.sh")], env=env, check=True)
        for path in outputs:
            if not path.is_file() or not path.stat().st_size:
                raise SystemExit(f"Incomplete smoke title: {path}")
    except (subprocess.CalledProcessError, SystemExit):
        # Notice staging happens after the link output exists. Retry the
        # packaging step after a failure instead of reusing a partial title.
        (native / "eboot.elf").unlink(missing_ok=True)
        raise
    return folder


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--stack", type=Path, required=True, help="directory containing the pinned PS5 checkouts")
    parser.add_argument("--prepare-only", action="store_true", help="generate the smoke sources without building")
    optional = parser.add_mutually_exclusive_group()
    optional.add_argument("--query-memory", dest="probe", action="store_const", const="query-memory",
                          help="include the optional QueryMemory SVC probe")
    optional.add_argument("--dualsense", dest="probe", action="store_const", const="dualsense",
                          help="include the optional DualSense input probe")
    optional.add_argument("--alias-subrange", dest="probe", action="store_const", const="alias-subrange",
                          help="include the optional alias ownership probe")
    optional.add_argument("--page-table", dest="probe", action="store_const", const="page-table",
                          help="include the optional page-table census probe")
    parser.add_argument("--unmapped-gpu-read", action="store_true",
                        help="with --page-table: also read reserved, unmapped VA on the GPU (faults the GPU and ends the title)")
    parser.add_argument("--prt-gpu-read", action="store_true",
                        help="with --page-table: read unmapped VA inside a PRT aperture on the GPU (may end the title)")
    parser.add_argument("--amm-pagetable-mib", type=int, default=0, metavar="MIB",
                        help='param.json "amm": {"pagetableMemorySizeInMib": MIB} (default: key absent)')
    parser.add_argument("--amm-multimap-gib", type=int, default=0, metavar="GIB",
                        help='param.json "amm": {"multimapVaRangeInGib": GIB} (default: key absent)')
    args = parser.parse_args()
    if (args.unmapped_gpu_read or args.prt_gpu_read) and args.probe != "page-table":
        parser.error("--unmapped-gpu-read and --prt-gpu-read need --page-table")
    defines = tuple(name for name, on in (("MKW_PT_UNMAPPED_GPU_READ", args.unmapped_gpu_read),
                                          ("MKW_PT_PRT_GPU_READ", args.prt_gpu_read)) if on)
    amm = {"pagetableMemorySizeInMib": args.amm_pagetable_mib, "multimapVaRangeInGib": args.amm_multimap_gib}
    stack = args.stack.resolve()
    template = stack / "PS5_VulkanTemplate"
    require_checkout(template, TEMPLATE)
    require_checkout(template / "external/glm", GLM)
    work = {"query-memory": QUERY_WORK, "dualsense": DUALSENSE_WORK, "alias-subrange": ALIAS_WORK,
            "page-table": PAGE_TABLE_WORK}.get(args.probe, WORK)
    title = work / "title"
    work.mkdir(parents=True, exist_ok=True)
    prepare(template, title, args.probe, amm)
    if args.prepare_only:
        print(title)
        return

    vulkan, mesa, sdk = (stack / name for name in ("PS5_Vulkan", "PS5_Mesa", "PS5_PayloadSDK"))
    for checkout, revision in ((vulkan, VULKAN), (mesa, MESA), (sdk, APP_SDK)):
        require_checkout(checkout, revision)
    print(build(title, vulkan, mesa, sdk, args.probe, defines))


if __name__ == "__main__":
    main()
